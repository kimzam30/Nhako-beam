// Android applicationId is io.github.kimzam30.nhakobeam (decided in Phase 2).
const KOTLIN_PACKAGE = 'io.github.kimzam30.nhakobeam.design';
const HEADER = 'GENERATED by design/tokens/build.mjs from tokens.json. Do not edit by hand.';

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const pascal = (s) => s[0].toUpperCase() + s.slice(1);
const round = (n, d = 4) => Number(n.toFixed(d));

// ---------- Spring physics ----------
// Displacement from rest for a unit step (0 -> 1), mass 1, starting at rest.
function springPosition(dampingRatio, stiffness) {
  const w0 = Math.sqrt(stiffness);
  const z = dampingRatio;
  if (z < 1) {
    const wd = w0 * Math.sqrt(1 - z * z);
    const b = -(z * w0) / wd;
    return (t) => 1 + Math.exp(-z * w0 * t) * (-Math.cos(wd * t) + b * Math.sin(wd * t));
  }
  if (z === 1) {
    return (t) => 1 + (-1 - w0 * t) * Math.exp(-w0 * t);
  }
  const s = Math.sqrt(z * z - 1);
  const r1 = -w0 * (z - s);
  const r2 = -w0 * (z + s);
  const c2 = r1 / (r2 - r1);
  const c1 = -1 - c2;
  return (t) => 1 + c1 * Math.exp(r1 * t) + c2 * Math.exp(r2 * t);
}

// Time in ms after which the spring stays within `threshold` of rest.
function settleMs(pos, threshold = 0.002) {
  let last = 0;
  for (let ms = 0; ms <= 5000; ms++) {
    if (Math.abs(pos(ms / 1000) - 1) > threshold) last = ms;
  }
  return Math.ceil((last + 1) / 10) * 10;
}

function springInfo(name, s) {
  const pos = springPosition(s.dampingRatio, s.stiffness);
  const duration = settleMs(pos);
  const samples = Math.min(60, Math.max(12, Math.round(duration / 16) + 1));
  const points = [];
  for (let i = 0; i < samples; i++) {
    const v = i === samples - 1 ? 1 : pos((duration / 1000) * (i / (samples - 1)));
    points.push(round(v, 4));
  }
  let peak = 0;
  for (let ms = 0; ms <= duration; ms++) peak = Math.max(peak, pos(ms / 1000));
  return {
    name,
    dampingRatio: s.dampingRatio,
    stiffness: s.stiffness,
    damping: round(2 * s.dampingRatio * Math.sqrt(s.stiffness), 3),
    settleMs: duration,
    overshootPct: round(Math.max(0, peak - 1) * 100, 1),
    cssLinear: `linear(${points.join(', ')})`,
    cssFallback: s.dampingRatio < 0.85 ? 'cubic-bezier(0.34, 1.36, 0.64, 1)' : 'cubic-bezier(0.2, 0, 0, 1)',
    use: s.use,
  };
}

const springs = Object.entries(t.motion.spring)
  .filter(([k]) => k !== 'note')
  .map(([k, v]) => springInfo(k, v));

// ---------- CSS ----------
function colorVars(theme) {
  const c = t.color[theme];
  const lines = Object.entries(c).map(([k, v]) => `  --color-${kebab(k)}: ${v};`);
  for (const [k, v] of Object.entries(t.elevation[theme])) lines.push(`  --elevation-${k}: ${v.css};`);
  lines.push(`  color-scheme: ${theme};`);
  return lines.join('\n');
}

function css() {
  const root = [];
  const px = (v) => (v === 0 ? '0' : `${v}px`);
  for (const [k, v] of Object.entries(t.brand)) {
    if (k !== 'note') root.push(`  --brand-${kebab(k)}: ${v};`);
  }
  root.push(`  --font-sans: ${t.font.sans.map((f) => (f.includes(' ') ? `"${f}"` : f)).join(', ')};`);
  root.push(`  --font-mono: ${t.font.mono.map((f) => (f.includes(' ') ? `"${f}"` : f)).join(', ')};`);
  for (const [k, v] of Object.entries(t.type)) {
    const n = kebab(k);
    root.push(`  --type-${n}-size: ${px(v.size)};`);
    root.push(`  --type-${n}-line: ${px(v.lineHeight)};`);
    root.push(`  --type-${n}-weight: ${v.weight};`);
    root.push(`  --type-${n}-tracking: ${v.tracking}em;`);
  }
  for (const [k, v] of Object.entries(t.space)) root.push(`  --space-${k}: ${px(v)};`);
  for (const [k, v] of Object.entries(t.radius)) root.push(`  --radius-${k}: ${px(v)};`);
  for (const [k, v] of Object.entries(t.size)) root.push(`  --size-${kebab(k)}: ${px(v)};`);
  for (const [k, v] of Object.entries(t.opacity)) root.push(`  --opacity-${kebab(k)}: ${v};`);
  for (const [k, v] of Object.entries(t.z)) root.push(`  --z-${kebab(k)}: ${v};`);
  for (const [k, v] of Object.entries(t.motion.duration)) {
    if (k !== 'note') root.push(`  --duration-${kebab(k)}: ${v}ms;`);
  }
  for (const [k, v] of Object.entries(t.motion.easing)) root.push(`  --ease-${kebab(k)}: cubic-bezier(${v.join(', ')});`);
  for (const [k, v] of Object.entries(t.motion.scale)) root.push(`  --scale-${kebab(k)}: ${v};`);
  for (const [k, v] of Object.entries(t.motion.distance)) root.push(`  --distance-${kebab(k)}: ${px(v)};`);
  root.push(`  --stagger-step: ${t.motion.stagger.step}ms;`);
  for (const s of springs) {
    root.push(`  --spring-${kebab(s.name)}: ${s.cssFallback};`);
    root.push(`  --spring-${kebab(s.name)}-duration: ${s.settleMs}ms;`);
  }
  root.push('  --motion-reduced: 0;');

  const linear = springs.map((s) => `    --spring-${kebab(s.name)}: ${s.cssLinear};`).join('\n');
  const typeClasses = Object.keys(t.type)
    .map((k) => {
      const n = kebab(k);
      return `.type-${n} {\n  font-size: var(--type-${n}-size);\n  line-height: var(--type-${n}-line);\n  font-weight: var(--type-${n}-weight);\n  letter-spacing: var(--type-${n}-tracking);\n}`;
    })
    .join('\n');

  return `/* ${HEADER} */

:root {
${root.join('\n')}
}

/* Springs as real CSS easing where supported (Chromium 113+, Safari 17.2+). */
@supports (transition-timing-function: linear(0, 1)) {
  :root {
${linear}
  }
}

:root,
[data-theme="light"] {
${colorVars('light')}
}

[data-theme="dark"] {
${colorVars('dark')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${colorVars('dark').replace(/^/gm, '  ')}
  }
}

/* Reduced motion: components read --motion-reduced (or matchMedia) and swap movement for fades. */
@media (prefers-reduced-motion: reduce) {
  :root:not([data-motion="full"]) {
    --motion-reduced: 1;
  }
}
[data-motion="reduced"] {
  --motion-reduced: 1;
}

.tabular {
  font-variant-numeric: tabular-nums;
  font-feature-settings: "${t.font.features.numbers}";
}

${typeClasses}
`;
}

// ---------- JS ----------
function jsData() {
  const spring = {};
  for (const s of springs) {
    spring[s.name] = {
      type: 'spring',
      stiffness: s.stiffness,
      damping: s.damping,
      mass: 1,
      dampingRatio: s.dampingRatio,
      settleMs: s.settleMs,
      overshootPct: s.overshootPct,
      css: s.cssLinear,
    };
  }
  const strip = (o) => Object.fromEntries(Object.entries(o).filter(([k]) => k !== 'note'));
  const haptic = Object.fromEntries(Object.entries(strip(t.haptic)));
  return {
    color: t.color,
    brand: strip(t.brand),
    font: { sans: t.font.sans, mono: t.font.mono },
    type: t.type,
    space: t.space,
    radius: t.radius,
    size: t.size,
    breakpoint: t.breakpoint,
    elevation: t.elevation,
    opacity: t.opacity,
    z: t.z,
    spring,
    duration: strip(t.motion.duration),
    easing: t.motion.easing,
    stagger: t.motion.stagger,
    scale: t.motion.scale,
    distance: t.motion.distance,
    gesture: t.gesture,
    haptic,
  };
}

function toTs(v, indent = '') {
  if (Array.isArray(v)) return `readonly [${v.map((x) => toTs(x, indent)).join(', ')}]`;
  if (v !== null && typeof v === 'object') {
    const inner = Object.entries(v)
      .map(([k, x]) => `${indent}  readonly ${/^[a-zA-Z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)}: ${toTs(x, indent + '  ')};`)
      .join('\n');
    return `{\n${inner}\n${indent}}`;
  }
  return JSON.stringify(v);
}

const data = jsData();
const js =
  `// ${HEADER}\n\n` +
  Object.entries(data)
    .map(([k, v]) => `export const ${k} = ${JSON.stringify(v, null, 2)};\n`)
    .join('\n');
const dts =
  `// ${HEADER}\n\n` +
  Object.entries(data)
    .map(([k, v]) => `export declare const ${k}: ${toTs(v)};\n`)
    .join('\n');

// ---------- Kotlin ----------
function ktColor(hex) {
  const h = hex.replace('#', '').toUpperCase();
  const argb = h.length === 8 ? h.slice(6) + h.slice(0, 6) : 'FF' + h;
  return `Color(0x${argb})`;
}
const kf = (n) => `${Number.isInteger(n) ? n : n}f`;
const kd = (n) => (n < 0 ? `(${n})` : `${n}`);

function kotlin() {
  const colorNames = Object.keys(t.color.light);
  const palette = (theme) =>
    colorNames.map((k) => `        ${k} = ${ktColor(t.color[theme][k])},`).join('\n');
  const typeLines = Object.entries(t.type)
    .map(([k, v]) => `    val ${k} = NhakoTypeToken(${v.size}.sp, ${v.lineHeight}.sp, FontWeight(${v.weight}), ${kd(v.tracking)}.em)`)
    .join('\n');
  const dpObject = (name, obj, prefix = '') =>
    `object ${name} {\n${Object.entries(obj)
      .map(([k, v]) => `    val ${prefix}${k} = ${v}.dp`)
      .join('\n')}\n}`;
  const springLines = springs
    .map((s) => `    /** ${s.use} Settles in about ${s.settleMs} ms, overshoot ${s.overshootPct}%. */\n    val ${s.name} = NhakoSpring(dampingRatio = ${kf(s.dampingRatio)}, stiffness = ${kf(s.stiffness)})`)
    .join('\n');
  const durations = Object.entries(t.motion.duration)
    .filter(([k]) => k !== 'note')
    .map(([k, v]) => `        const val ${k} = ${v}`)
    .join('\n');
  const easings = Object.entries(t.motion.easing)
    .map(([k, v]) => `        val ${k} = CubicBezierEasing(${v.map(kf).join(', ')})`)
    .join('\n');
  const scales = Object.entries(t.motion.scale)
    .map(([k, v]) => `        const val ${k} = ${kf(v)}`)
    .join('\n');
  const distances = Object.entries(t.motion.distance)
    .map(([k, v]) => `        val ${k} = ${v}.dp`)
    .join('\n');
  const gestureUnits = { dragSlopPointer: 'dp', dragSlopTouch: 'dp', swipeCommitVelocity: 'dp/s', swipeFlyOutVelocityMin: 'dp/s', magnetRadius: 'dp', magnetSnapRadius: 'dp', longPressMs: 'ms', sheetDismissVelocity: 'dp/s', swipeMaxRotationDeg: 'degrees' };
  const gestures = Object.entries(t.gesture)
    .map(([k, v]) => `    const val ${k} = ${k.endsWith('Ms') ? v : kf(v)}${gestureUnits[k] ? ` // ${gestureUnits[k]}` : ''}`)
    .join('\n');
  const hc = (name) => (name === 'none' ? 'null' : `HapticFeedbackConstants.${name}`);
  const haptics = Object.entries(t.haptic)
    .filter(([k]) => k !== 'note')
    .map(([k, v]) => `    ${pascal(k)}(${hc(v.android)}, ${v.minApi}, ${hc(v.fallback)})`)
    .join(',\n');
  const elevation = Object.entries(t.elevation.light)
    .map(([k, v]) => `    val level${k} = ${v.dp}.dp`)
    .join('\n');

  return `// ${HEADER}
package ${KOTLIN_PACKAGE}

import android.os.Build
import android.view.HapticFeedbackConstants
import android.view.View
import androidx.compose.animation.core.CubicBezierEasing
import androidx.compose.animation.core.SpringSpec
import androidx.compose.animation.core.spring
import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.TextUnit
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.em
import androidx.compose.ui.unit.sp

@Immutable
data class NhakoColors(
${colorNames.map((k) => `    val ${k}: Color,`).join('\n')}
)

/** The logo's colors, the same in light and dark (icon, splash, beam glow). */
object NhakoBrand {
${Object.entries(t.brand).filter(([k]) => k !== 'note').map(([k, v]) => `    val ${k} = ${ktColor(v)}`).join('\n')}
}

object NhakoPalette {
    val Light = NhakoColors(
${palette('light')}
    )
    val Dark = NhakoColors(
${palette('dark')}
    )
}

@Immutable
data class NhakoTypeToken(
    val size: TextUnit,
    val lineHeight: TextUnit,
    val weight: FontWeight,
    val tracking: TextUnit,
)

object NhakoType {
${typeLines}
}

${dpObject('NhakoSpace', t.space, 's')}

${dpObject('NhakoRadius', t.radius)}

${dpObject('NhakoSize', t.size)}

${dpObject('NhakoBreakpoint', t.breakpoint)}

object NhakoElevation {
${elevation}
}

object NhakoOpacity {
${Object.entries(t.opacity).map(([k, v]) => `    const val ${k} = ${kf(v)}`).join('\n')}
}

@Immutable
data class NhakoSpring(val dampingRatio: Float, val stiffness: Float) {
    fun <T> spec(visibilityThreshold: T? = null): SpringSpec<T> =
        spring(dampingRatio = dampingRatio, stiffness = stiffness, visibilityThreshold = visibilityThreshold)
}

object NhakoMotion {
${springLines}

    object Duration {
${durations}
    }

    object Easing {
${easings}
    }

    object Scale {
${scales}
    }

    object Distance {
${distances}
    }

    const val staggerStepMs = ${t.motion.stagger.step}
    const val staggerMaxItems = ${t.motion.stagger.maxItems}
}

object NhakoGesture {
${gestures}
}

/** Haptic events. Null constant means stay silent on purpose. */
enum class NhakoHaptic(private val constant: Int?, private val minApi: Int, private val fallback: Int?) {
${haptics};

    fun perform(view: View) {
        val c = if (Build.VERSION.SDK_INT >= minApi) constant else fallback
        if (c != null) view.performHapticFeedback(c)
    }
}
`;
}

writeFileSync(join(outDir, 'tokens.css'), css());
writeFileSync(join(outDir, 'tokens.js'), js);
writeFileSync(join(outDir, 'tokens.d.ts'), dts);
writeFileSync(join(outDir, 'NhakoTokens.kt'), kotlin());

console.table(springs.map(({ name, dampingRatio, stiffness, damping, settleMs, overshootPct }) => ({ name, dampingRatio, stiffness, damping, settleMs, overshootPct })));
console.log(`Wrote tokens.css, tokens.js, tokens.d.ts, NhakoTokens.kt to ${outDir}`);
