// Builds the icon set for both apps from icons.mjs.
// Usage: node design/icons/build.mjs   (or `npm run icons` in desktop/)
// Output (design/icons/build/):
//   icons.js, icons.d.ts                  the drawings for the desktop app (Icon.svelte)
//   kotlin/NhakoIcons.kt                  the same for Android (PhIcon in ui/theme/Theme.kt)
//   res/drawable/nb_share_*.xml           four device icons as vector drawables, for Direct Share
//                                         shortcuts, which need a real drawable (cut-outs become holes)
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SET } from './icons.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, 'build');
const HEADER = 'GENERATED by design/icons/build.mjs from icons.mjs. Do not edit by hand.';
const NAVY = '#1A6FE0', DEEP = '#0B3E85';

// One normalised shape per icon: s solid, b bold, k knock, t top strokes, f top fills, r round.
const norm = (list, w) => (list ?? []).map((x) => (typeof x === 'string' ? { d: x, w } : { d: x.d, w: x.w ?? w }));
const icons = Object.fromEntries(Object.entries(SET).map(([name, i]) => [name, {
  s: i.solid ?? [],
  b: norm(i.bold, 3),
  k: norm(i.knock, 2.2),
  t: (i.top ?? []).filter((x) => !x.fill).map((x) => ({ d: x.d, w: x.w ?? 3 })),
  f: (i.top ?? []).filter((x) => x.fill).map((x) => x.fill),
  r: !!i.round,
}]));

for (const [name, i] of Object.entries(icons)) {
  for (const d of [...i.s, ...i.b.map((x) => x.d), ...i.k.map((x) => x.d), ...i.t.map((x) => x.d), ...i.f]) {
    if (!/^[MmLlHhVvCcSsQqTtAaZz0-9.,\s-]+$/.test(d)) throw new Error(`${name}: unexpected path data ${d}`);
  }
}

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'kotlin'), { recursive: true });
mkdirSync(join(out, 'res/drawable'), { recursive: true });

// Desktop
writeFileSync(join(out, 'icons.js'), `// ${HEADER}
export const OFFSET = { navy: '${NAVY}', deep: '${DEEP}' };
export const ICONS = ${JSON.stringify(icons, null, 1)};
`);
writeFileSync(join(out, 'icons.d.ts'), `// ${HEADER}
export interface IconStroke { d: string; w: number }
export interface IconDrawing {
  /** Filled paths, evenodd. */ s: string[];
  /** Thick strokes. */ b: IconStroke[];
  /** Strokes cut out of s and b. */ k: IconStroke[];
  /** Strokes drawn after the cut-outs. */ t: IconStroke[];
  /** Fills drawn after the cut-outs. */ f: string[];
  /** Round shape: may reach 1..23 instead of 2..22. */ r: boolean;
}
export declare const OFFSET: { navy: string; deep: string };
export declare const ICONS: Record<string, IconDrawing>;
`);

// Android
const ks = (s) => `"${s}"`;
const kStrokes = (l) => (l.length ? `listOf(${l.map((x) => `S(${ks(x.d)}, ${x.w}f)`).join(', ')})` : 'emptyList()');
const kStrings = (l) => (l.length ? `listOf(${l.map(ks).join(', ')})` : 'emptyList()');
writeFileSync(join(out, 'kotlin/NhakoIcons.kt'), `// ${HEADER}
package io.github.kimzam30.nhakobeam.design

/** The icon set (style B), drawn by PhIcon in ui/theme/Theme.kt. Same data as the desktop app. */
object NhakoIcons {
    /** A stroke: path data on the 24 grid and its width in grid units. */
    class S(val d: String, val w: Float)

    /** solid: filled, evenodd. bold: thick strokes. knock: cut out of both. top / topFill: drawn after the cut-outs. */
    class Glyph(val solid: List<String>, val bold: List<S>, val knock: List<S>, val top: List<S>, val topFill: List<String>, val round: Boolean)

    const val OFFSET_NAVY = 0xFF${NAVY.slice(1)}
    const val OFFSET_DEEP = 0xFF${DEEP.slice(1)}

    val all: Map<String, Glyph> by lazy { build() }

    private fun build(): Map<String, Glyph> = hashMapOf(
${Object.entries(icons).map(([n, i]) => `        "${n}" to Glyph(${kStrings(i.s)}, ${kStrokes(i.b)}, ${kStrokes(i.k)}, ${kStrokes(i.t)}, ${kStrings(i.f)}, ${i.r}),`).join('\n')}
    )
}
`);

// Direct Share drawables: solids only, with each cut-out turned into a hole in the shape it sits on.
// Knocks here are short lines (a rounded bar) or dots (a circle); anything else is refused.
const circ = (cx, cy, r) => `M${cx - r},${cy}a${r},${r} 0 1,0 ${2 * r},0a${r},${r} 0 1,0 ${-2 * r},0Z`;
function hole(k) {
  let m = k.d.match(/^M([\d.]+) ([\d.]+)v\.01$/);
  if (m) return circ(+m[1], +m[2], k.w / 2);
  m = k.d.match(/^M([\d.]+) ([\d.]+)H([\d.]+)$/);
  if (m) { const [x1, y, x2] = [+m[1], +m[2], +m[3]], r = k.w / 2; return `M${x1},${y - r}H${x2}A${r},${r} 0 0,1 ${x2},${y + r}H${x1}A${r},${r} 0 0,1 ${x1},${y - r}Z`; }
  throw new Error(`can't turn ${k.d} into a hole`);
}
const SHARE = { laptop: {}, 'desktop-tower': { holesIn: 2 }, 'device-mobile': {}, 'device-tablet': {} };
for (const [name, o] of Object.entries(SHARE)) {
  const i = icons[name];
  const paths = i.s.map((d, idx) => (idx === o.holesIn ? d + i.k.map(hole).join('') : d));
  if (o.holesIn === undefined && i.k.length) throw new Error(`${name} has cut-outs but no shape to put them in`);
  writeFileSync(join(out, `res/drawable/nb_share_${name.replace(/-/g, '_')}.xml`), `<?xml version="1.0" encoding="utf-8"?>
<!-- ${HEADER} Icon "${name}" for Direct Share shortcuts. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">
${paths.map((d) => `    <path android:fillColor="#FF000000" android:fillType="evenOdd" android:pathData="${d}" />`).join('\n')}
</vector>
`);
}
console.log(`icons: ${Object.keys(icons).length} drawings, ${Object.keys(SHARE).length} share drawables -> ${out}`);
