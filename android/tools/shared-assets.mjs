// Makes the Android app's copies of what the desktop app already has, so both stay the same:
//  - every UI string in desktop/src/lib/copy.ts -> app/src/main/kotlin/.../ui/Copy.kt
//  - the 256 code words in core/src/words.txt -> app/src/main/kotlin/.../ui/Words.kt
//  - the Phosphor icons listed in desktop/src/lib/icons/icons.ts (plus a few Android-only ones)
//    that the Android code names somewhere -> app/src/main/res/drawable/ph_<name>_<weight>.xml
//    vector drawables, and res/raw/keep.xml so lint knows they're used (PhIcon finds them by name)
// Run from anywhere after `npm install` in desktop/:  node android/tools/shared-assets.mjs
// SharedCopyTest (app/src/test) fails when Copy.kt is out of date with copy.ts.
import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '../..');
const app = join(root, 'android/app/src/main');
const phosphor = join(root, 'desktop/node_modules/@phosphor-icons/core/assets');

// ---------- Copy ----------

const copySource = readFileSync(join(root, 'desktop/src/lib/copy.ts'), 'utf8');
const body = copySource.slice(copySource.indexOf('export const copy = {'), copySource.indexOf('} as const;'));
// Entries are 'key': 'text' or 'key': "text", possibly with the text on the next line.
const entries = [...body.matchAll(/'([a-zA-Z0-9.]+)':\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)")/g)].map((m) => [
  m[1],
  (m[2] ?? m[3]).replace(/\\'/g, "'").replace(/\\"/g, '"'),
]);
if (entries.length < 100) throw new Error(`only found ${entries.length} strings in copy.ts`);
const kotlinString = (s) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$') + '"';
const copyKt = `// GENERATED by android/tools/shared-assets.mjs from desktop/src/lib/copy.ts. Do not edit by hand.
package io.github.kimzam30.nhakobeam.ui

/** Every UI string, the same as the desktop app's. Placeholders look like {device}. */
object Copy {
    val strings: Map<String, String> = mapOf(
${entries.map(([k, v]) => `        ${kotlinString(k)} to ${kotlinString(v)},`).join('\n')}
    )

    /** The string for [key], with {name} placeholders filled from [vars]. */
    fun t(key: String, vararg vars: Pair<String, Any>): String {
        var s = strings[key] ?: error("No string for \\"$key\\"")
        for ((name, value) in vars) s = s.replace("{$name}", value.toString())
        return s
    }
}
`;
const copyPath = join(app, 'kotlin/io/github/kimzam30/nhakobeam/ui/Copy.kt');
mkdirSync(dirname(copyPath), { recursive: true });
writeFileSync(copyPath, copyKt);

// ---------- Code words ----------

const words = readFileSync(join(root, 'core/src/words.txt'), 'utf8').split('\n').map((w) => w.trim()).filter((w) => w && !w.startsWith('#'));
if (words.length !== 256) throw new Error(`expected 256 code words, found ${words.length}`);
const wordsKt = `// GENERATED by android/tools/shared-assets.mjs from core/src/words.txt. Do not edit by hand.
package io.github.kimzam30.nhakobeam.ui

/** The 256 code words, the same list as the engine's. */
object Words {
    val all: List<String> = listOf(
${words.map((w) => `        ${kotlinString(w)},`).join('\n')}
    )
    private val set = all.toHashSet()

    fun isWord(w: String) = w.trim().lowercase() in set

    /** Words starting with [prefix], for the autocomplete under each slot. */
    fun complete(prefix: String, max: Int = 3): List<String> {
        val p = prefix.trim().lowercase()
        if (p.isEmpty()) return emptyList()
        return all.filter { it.startsWith(p) && it != p }.take(max)
    }
}
`;
writeFileSync(join(app, 'kotlin/io/github/kimzam30/nhakobeam/ui/Words.kt'), wordsKt);

// ---------- Icons ----------

const iconsTs = readFileSync(join(root, 'desktop/src/lib/icons/icons.ts'), 'utf8');
const listed = (weight) => {
  const m = iconsTs.match(new RegExp(`assets/${weight}/\\{([^}]+)\\}-${weight}\\.svg`));
  return m ? m[1].split(',') : [];
};
// Android-only: the camera for scanning, the files picker, and letting the app run in the background.
const extra = { duotone: ['camera', 'camera-slash', 'image', 'flashlight', 'battery-charging'], fill: [], bold: ['arrow-left'] };
// Icons are named in Kotlin as plain strings ("paper-plane-tilt"); only those are bundled.
const named = new Set();
(function walk(dir) {
  for (const f of readdirSync(dir)) {
    const path = join(dir, f);
    if (statSync(path).isDirectory()) walk(path);
    else if (f.endsWith('.kt') && f !== 'Copy.kt' && f !== 'Words.kt') {
      for (const m of readFileSync(path, 'utf8').matchAll(/"([a-z][a-z0-9-]*)"/g)) named.add(m[1]);
    }
  }
})(join(app, 'kotlin'));
const drawables = join(app, 'res/drawable');
mkdirSync(drawables, { recursive: true });
for (const f of readdirSync(drawables)) if (f.startsWith('ph_')) rmSync(join(drawables, f));
let count = 0;
for (const weight of ['duotone', 'fill', 'bold']) {
  for (const name of new Set([...listed(weight), ...extra[weight]])) {
    if (!named.has(name)) continue;
    const svg = readFileSync(join(phosphor, weight, `${name}-${weight}.svg`), 'utf8');
    const paths = [...svg.matchAll(/<path d="([^"]+)"(?: opacity="([0-9.]+)")?\/>/g)].map(
      ([, d, opacity]) =>
        `    <path android:fillColor="#FF000000"${opacity ? ` android:fillAlpha="${opacity}"` : ''} android:pathData="${d}" />`,
    );
    if (!paths.length) throw new Error(`no paths in ${name}-${weight}.svg`);
    const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Phosphor icon "${name}" (${weight}), MIT licence. Generated by android/tools/shared-assets.mjs. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="256"
    android:viewportHeight="256">
${paths.join('\n')}
</vector>
`;
    writeFileSync(join(drawables, `ph_${name.replace(/-/g, '_')}_${weight}.xml`), xml);
    count++;
  }
}
mkdirSync(join(app, 'res/raw'), { recursive: true });
writeFileSync(
  join(app, 'res/raw/keep.xml'),
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by android/tools/shared-assets.mjs. PhIcon looks the icons up by name, which lint can't see. -->
<resources xmlns:tools="http://schemas.android.com/tools" tools:keep="@drawable/ph_*" />
`,
);
console.log(`Copy.kt: ${entries.length} strings. Words.kt: ${words.length} words. Icons: ${count} drawables.`);
